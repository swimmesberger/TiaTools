namespace TiaFormat.Program;

/// <summary>What an HMI script is attached to: an event of a screen or screen item, or a property of a screen item.</summary>
public enum TiaHmiScriptKind : byte {
    Event,
    Property,
}

/// <summary>
/// A Unified HMI script: on <see cref="Screen"/>, or on its screen item <see cref="Item"/>; <see cref="Name"/> is the
/// event (<c>Tapped</c>) or property (<c>BackColor</c>); <see cref="Code"/> is its body as TIA's editor shows it.
/// </summary>
public sealed record TiaHmiScript(string Screen, string? Item, TiaHmiScriptKind Kind, string Name, string Language, string Code);

/// <summary>A global script module of a Unified device, its code joined as TIA exports it (<c>&lt;name&gt;.hmi.js</c>).</summary>
public sealed record TiaHmiScriptModule(string Name, string Language, IReadOnlyList<string> Functions, string Code);

/// <summary>A parameter of a VB script: its name and declaration (<c>ByVal</c>, <c>ByRef</c>).</summary>
public readonly record struct TiaHmiVbParameter(string Name, string Declaration);

/// <summary>A VB script of a Comfort/Advanced device: <c>Sub</c> or <c>Function</c>, its parameters and its code, with every name in place.</summary>
public sealed record TiaHmiVbScript(string Name, string? Folder, string? ReturnType, IReadOnlyList<TiaHmiVbParameter> Parameters, string? PreCode, string Code);

/// <summary>One file of a custom web control's package: its path in the package and its bytes.</summary>
public sealed record TiaHmiPackageFile(string Path, byte[] Content) {
    /// <summary>A text file of the package (HTML, CSS, JavaScript, JSON) as UTF-8 text; null for any other.</summary>
    public string? Text => IsText(Path) ? Encoding.UTF8.GetString(Content) : null;

    internal static bool IsText(string path) =>
        System.IO.Path.GetExtension(path).ToLowerInvariant() is ".html" or ".htm" or ".css" or ".js" or ".mjs" or ".json" or ".txt" or ".svg" or ".xml" or ".md";
}

/// <summary>
/// A custom web control of a Unified device: its GUID and display name, the screen items it is used by, the path of its
/// package in the project, and the package's files, which an archive keeps in <c>UserFiles/CustomControls</c>.
/// </summary>
public sealed record TiaHmiCustomWebControl(string Guid, string? DisplayName, IReadOnlyList<(string Screen, string Item)> UsedBy, string PackagePath, IReadOnlyList<TiaHmiPackageFile> Files) {
    /// <summary>Whether the package was found in the archive.</summary>
    public bool HasPackage => Files.Count != 0;
}

/// <summary>An HMI device's own code (spec 0017).</summary>
public sealed record TiaHmiCode(
    IReadOnlyList<TiaHmiScript> Scripts,
    IReadOnlyList<TiaHmiScriptModule> Modules,
    IReadOnlyList<TiaHmiVbScript> VbScripts,
    IReadOnlyList<TiaHmiCustomWebControl> CustomWebControls) {
    public static TiaHmiCode Empty { get; } = new([], [], [], []);

    public bool IsEmpty => Scripts.Count == 0 && Modules.Count == 0 && VbScripts.Count == 0 && CustomWebControls.Count == 0;
}

/// <summary>
/// Reads the code of an HMI device (spec 0017, format page section 24): Unified HMI scripts and global script modules,
/// Comfort/Advanced VB scripts, and custom web controls. Reading never runs any of it.
/// </summary>
internal sealed partial class TiaHmiCodeReader {
    private const string Core = "Siemens.Automation.ObjectFrame.ICoreAttributes";
    private const string Scripting = "Siemens.Simatic.Hmi.DL.Scripting.";
    private const string Utah = "Siemens.Simatic.Hmi.Utah.";

    /// <summary>The header TIA writes between a module's global definition area and its functions.</summary>
    internal const string GlobalAreaEnd = "/*<auto-generated>\n***End of Global definition area***\nChanges to this comment may cause incorrect behavior during document based import.\n</auto-generated>*/";

    private readonly TiaProgram _program;
    private readonly TiaDatabase _db;
    private readonly TiaAttributeHandle _name, _subtype, _code, _language, _scope, _functionName, _parameters, _exported, _async, _idCode, _preIdCode, _vbParameters, _returnType, _filePath;
    private readonly TiaRelationHandle _target, _containerParent, _events, _triggers, _scriptParent, _expandoReferences, _globalSection, _elements, _codeRelations, _folder;
    private readonly uint? _container, _embedded, _module, _section, _global, _vb, _systemFunction, _screen, _item, _resource;

    public TiaHmiCodeReader(TiaProgram program) {
        _program = program;
        _db = program.Database;
        var s = _db.Schema;
        _name = s.Attribute(Core, "Name");
        _subtype = s.Attribute(Core, "Subtype");
        _code = s.Attribute(Scripting + "IScriptAttributes", "Code");
        _language = s.Attribute(Scripting + "IScriptAttributes", "Language");
        _scope = s.Attribute(Scripting + "IScriptAttributes", "Scope");
        _functionName = s.Attribute(Scripting + "IScriptSignatureAttributes", "FunctionName");
        _parameters = s.Attribute(Scripting + "IScriptSignatureAttributes", "ParameterList");
        _exported = s.Attribute(Scripting + "IScriptSignatureAttributes", "IsExported");
        _async = s.Attribute(Scripting + "IScriptSignatureAttributes", "IsAsync");
        _idCode = s.Attribute(Utah + "Scripting.ISimpleBaseScriptAttributes", "IdCode");
        _preIdCode = s.Attribute(Utah + "Scripting.IBaseScriptAttributes", "PreIdCode");
        _vbParameters = s.Attribute(Utah + "Scripting.IBaseScriptAttributes", "ParameterList");
        _returnType = s.Attribute(Utah + "Scripting.IVBScriptAttributes", "ReturnType");
        _filePath = s.Attribute(Utah + "Globalization.IHmiDynamicScreenItemResourceAttributes", "FilePath");
        _target = s.Relation("Target");
        _containerParent = s.Relation("ScriptContainerParent");
        _events = s.Relation("EventElements");
        _triggers = s.Relation("TriggerElements");
        _scriptParent = s.Relation("EmbeddedScriptParent");
        _expandoReferences = s.Relation("ExpandoReferences");
        _globalSection = s.Relation("GlobalSection");
        _elements = s.Relation("Elements");
        _codeRelations = s.Relation("CodeRelations");
        _folder = s.Relation("AggregatingFolder");
        _container = s.FindObjectType(Scripting + "HmiScriptModuleContainerData")?.Id;
        _embedded = s.FindObjectType(Scripting + "HmiScriptEmbeddedData")?.Id;
        _module = s.FindObjectType(Scripting + "HmiScriptGlobalModuleData")?.Id;
        _section = s.FindObjectType(Scripting + "HmiScriptGlobalSectionData")?.Id;
        _global = s.FindObjectType(Scripting + "HmiScriptGlobalData")?.Id;
        _vb = s.FindObjectType(Utah + "Scripting.HmiVBScriptGlobalData")?.Id;
        _systemFunction = s.FindObjectType(Utah + "Scripting.HmiSystemFunctionData")?.Id;
        _screen = s.FindObjectType("Siemens.Simatic.Hmi.DL.ModernUI.ILScreenData")?.Id;
        _item = s.FindObjectType("Siemens.Simatic.Hmi.DL.ModernUI.ILScreenItemData")?.Id;
        _resource = s.FindObjectType(Utah + "Globalization.HmiDynamicScreenItemResourceData")?.Id;
    }

    /// <summary>The code of every HMI application among <paramref name="applications"/>, by its object id.</summary>
    public Dictionary<ulong, TiaHmiCode> Read(IReadOnlyCollection<ulong> applications) {
        var scripts = new Dictionary<ulong, List<TiaHmiScript>>();
        var modules = new Dictionary<ulong, List<TiaHmiScriptModule>>();
        var vb = new Dictionary<ulong, List<TiaHmiVbScript>>();
        var controls = new Dictionary<ulong, Dictionary<string, (string? Display, List<(string, string)> Uses, string Path)>>();
        foreach (ref readonly var frame in _db.Frames) {
            if (frame.TypeId != _container && frame.TypeId != _module && frame.TypeId != _vb && frame.TypeId != _item) {
                continue;
            }
            if (!_db.TryGetTarget(frame, _target, out var owner) || !applications.Contains(owner.ObjectId)) {
                continue;
            }
            var id = owner.ObjectId;
            if (frame.TypeId == _container) {
                ReadContainer(frame, Of(scripts, id));
            } else if (frame.TypeId == _module) {
                Of(modules, id).Add(ReadModule(frame));
            } else if (frame.TypeId == _vb) {
                Of(vb, id).Add(ReadVbScript(frame));
            } else if (_db.ReadString(frame, _subtype) == "HmiCustomWebControlContainer") {
                NoteControl(frame, Of(controls, id));
            }
        }
        var result = new Dictionary<ulong, TiaHmiCode>();
        foreach (var id in applications) {
            result[id] = new TiaHmiCode(
                [.. scripts.GetValueOrDefault(id, []).OrderBy(script => script.Screen, StringComparer.Ordinal).ThenBy(script => script.Item ?? "", StringComparer.Ordinal)
                    .ThenBy(script => script.Kind).ThenBy(script => script.Name, StringComparer.Ordinal)],
                [.. modules.GetValueOrDefault(id, []).OrderBy(module => module.Name, StringComparer.Ordinal)],
                [.. vb.GetValueOrDefault(id, []).OrderBy(script => script.Name, StringComparer.Ordinal)],
                [.. controls.GetValueOrDefault(id, []).OrderBy(entry => entry.Key, StringComparer.Ordinal)
                    .Select(entry => new TiaHmiCustomWebControl(entry.Key, entry.Value.Display, entry.Value.Uses, entry.Value.Path, ReadPackage(entry.Value.Path)))]);
        }
        return result;

        static TList Of<TList>(Dictionary<ulong, TList> lists, ulong id) where TList : new() =>
            lists.TryGetValue(id, out var list) ? list : lists[id] = new TList();
    }

    // Unified scripts ---------------------------------------------------------------------------------------------------

    /// <summary>A screen's script container: its event scripts and its property scripts.</summary>
    private void ReadContainer(in TiaFrame container, List<TiaHmiScript> into) {
        var screenName = _db.TryGetTarget(container, _containerParent, out var screen) ? _db.ReadString(screen, _name) ?? "" : "";
        foreach (var relation in _db.EnumerateRelations(container)) {
            var kind = _events.Matches(relation.RelationId) ? TiaHmiScriptKind.Event : _triggers.Matches(relation.RelationId) ? TiaHmiScriptKind.Property : (TiaHmiScriptKind?)null;
            if (kind is null || relation.Target.TypeId != _embedded || !_db.TryGetFrame(relation.Target, out var script)) {
                continue;
            }
            string? item = null;
            if (_db.TryGetTarget(script, _scriptParent, out var parent) && parent.TypeId == _item) {
                item = _db.ReadString(parent, _name);
            }
            var name = _db.ReadString(script, _name) ?? "";
            // TIA names an event script On<event> and a property script <property>Trigger.
            name = kind == TiaHmiScriptKind.Event
                ? name.StartsWith("On", StringComparison.Ordinal) ? name[2..] : name
                : name.EndsWith("Trigger", StringComparison.Ordinal) ? name[..^"Trigger".Length] : name;
            into.Add(new TiaHmiScript(screenName, item, kind.Value, name, _db.ReadString(script, _language) ?? "JavaScript", ReadCode(script, _code)));
        }
    }

    /// <summary>
    /// A <c>CodePartList</c> joined: each part is text, or a reference whose text is a number. The object's simple expando
    /// names those numbers in the order of its <c>ExpandoReferences</c>, so a reference reads as that object's name.
    /// </summary>
    private string ReadCode(in TiaFrame frame, TiaAttributeHandle attribute) {
        var value = _db.ReadValueBytes(frame, attribute);
        if (value.IsEmpty) {
            return "";
        }
        Dictionary<string, string>? names = null;
        var text = new StringBuilder();
        foreach (var element in Elements(value)) {
            var data = StringField(value, element, 0) ?? "";
            var isReference = element + 8 < value.Length && value[element + 8] != 0;
            if (isReference) {
                names ??= ReferenceNames(frame);
                text.Append(names.GetValueOrDefault(data, data));
            } else {
                text.Append(data);
            }
        }
        // TIA stores lines ending in CR LF; the reader's text ends them in LF, as its other text does.
        return text.Replace("\r\n", "\n").ToString();
    }

    /// <summary>
    /// What each reference of an object's code stands for. Each reference has its own numbered value in the object's
    /// simple expando (besides its own values, such as Signature and Code): u32 size 6, then a u16 index into the
    /// object's <c>ExpandoReferences</c>, which hold each object referred to once.
    /// </summary>
    private Dictionary<string, string> ReferenceNames(in TiaFrame frame) {
        var targets = new List<string>();
        foreach (var relation in _db.EnumerateRelations(frame)) {
            if (_expandoReferences.Matches(relation.RelationId)) {
                targets.Add(_db.TryGetFrame(relation.Target, out var target) ? _db.ReadString(target, _name) ?? "" : "");
            }
        }
        var names = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var (key, _, value) in _db.ReadSimpleExpandoValues(frame)) {
            if (value.Length >= 6 && BinaryPrimitives.ReadInt32LittleEndian(value) == 6
                && BinaryPrimitives.ReadUInt16LittleEndian(value.AsSpan(4)) is var index && index < targets.Count) {
                names[key] = targets[index];
            }
        }
        return names;
    }

    // Global script modules --------------------------------------------------------------------------------------------

    /// <summary>
    /// A module as TIA exports it: its global definition area as stored, which ends in TIA's end-of-area comment (added
    /// where it does not), then each function: its signature, its stored body, which starts with its own line break,
    /// and a closing brace.
    /// </summary>
    private TiaHmiScriptModule ReadModule(in TiaFrame module) {
        var area = "";
        var functions = new List<(string Name, string Text)>();
        foreach (var relation in _db.EnumerateRelations(module)) {
            if (!_db.TryGetFrame(relation.Target, out var part)) {
                continue;
            }
            if (_globalSection.Matches(relation.RelationId) && part.TypeId == _section) {
                area = ReadCode(part, _code);
            } else if (_elements.Matches(relation.RelationId) && part.TypeId == _global) {
                var name = ReadCode(part, _functionName);
                if (name.Length == 0) {
                    name = _db.ReadString(part, _name) ?? "";
                }
                var signature = (_db.ReadBoolean(part, _exported) ? "export " : "") + (_db.ReadBoolean(part, _async) ? "async " : "")
                    + "function " + name + "(" + string.Join(", ", Parameters(part)) + ") {";
                functions.Add((name, signature + ReadCode(part, _code) + "\n}\n"));
            }
        }
        var code = new StringBuilder(area.TrimEnd('\n'));
        if (!area.TrimEnd('\n').EndsWith(GlobalAreaEnd, StringComparison.Ordinal)) {
            code.Append(code.Length == 0 ? "" : "\n").Append(GlobalAreaEnd);
        }
        code.Append('\n');
        foreach (var function in functions) {
            code.Append(function.Text);
        }
        return new TiaHmiScriptModule(_db.ReadString(module, _name) ?? "", "JavaScript", [.. functions.Select(function => function.Name)], code.ToString());
    }

    /// <summary>A function's parameter names: <c>ParameterList</c>, an array of (DataType, Information, Name).</summary>
    private List<string> Parameters(in TiaFrame function) {
        var value = _db.ReadValueBytes(function, _parameters);
        var names = new List<string>();
        foreach (var element in Elements(value)) {
            names.Add(StringField(value, element, 2) ?? "");
        }
        return names;
    }

    // VB scripts -------------------------------------------------------------------------------------------------------

    /// <summary>
    /// A VB script: <c>IdCode</c> with every name replaced by <c>$k$i$</c>, where <c>i</c> indexes the script's
    /// <c>CodeRelations</c> (the script itself first, then the HMI tags and system functions it uses) and <c>k</c> says
    /// how the name is written: 4 in quotes, as <c>SmartTags("Speed")</c> takes it, any other bare.
    /// </summary>
    private TiaHmiVbScript ReadVbScript(in TiaFrame script) {
        var related = new List<string>();
        foreach (var relation in _db.EnumerateRelations(script)) {
            if (!_codeRelations.Matches(relation.RelationId)) {
                continue;
            }
            var name = _db.TryGetFrame(relation.Target, out var target) ? _db.ReadString(target, _name) ?? "" : "";
            if (relation.Target.TypeId == _systemFunction) {
                // A system function is stored by its GUID only; its name is TIA's own.
                name = SystemFunctions.GetValueOrDefault(name.ToLowerInvariant(), "SystemFunction_" + name);
            }
            related.Add(name);
        }
        var parameters = new List<TiaHmiVbParameter>();
        var list = _db.ReadValueBytes(script, _vbParameters);
        foreach (var element in Elements(list)) {
            parameters.Add(new TiaHmiVbParameter(StringField(list, element, 1) ?? "", StringField(list, element, 0) ?? ""));
        }
        var folder = _program.FolderPath(script);
        var slash = folder.IndexOf('/', StringComparison.Ordinal);
        return new TiaHmiVbScript(
            _db.ReadString(script, _name) ?? "",
            slash < 0 ? null : folder[(slash + 1)..],
            _db.ReadString(script, _returnType),
            parameters,
            Names(_db.ReadString(script, _preIdCode)) is { } pre && !string.IsNullOrWhiteSpace(pre) ? pre : null,
            Names(_db.ReadString(script, _idCode)) ?? "");

        string? Names(string? code) => code is null ? null : Placeholder().Replace(code.Replace("\r\n", "\n", StringComparison.Ordinal), match =>
            int.TryParse(match.Groups[2].ValueSpan, out var index) && index < related.Count
                ? match.Groups[1].ValueSpan is "4" ? "\"" + related[index] + "\"" : related[index]
                : match.Value);
    }

    /// <summary>The names of system functions by the GUID TIA stores for them; those the reference projects check.</summary>
    private static readonly Dictionary<string, string> SystemFunctions = new(StringComparer.Ordinal) {
        ["bfde4b54-0db7-4817-8032-87127bf19bb9"] = "ShowSystemAlarm",
    };

    [GeneratedRegex(@"\$(\d+)\$(\d+)\$", RegexOptions.CultureInvariant)]
    private static partial Regex Placeholder();

    // Custom web controls ----------------------------------------------------------------------------------------------

    /// <summary>A screen item that holds a custom web control: its resource names the control's GUID and package.</summary>
    private void NoteControl(in TiaFrame item, Dictionary<string, (string? Display, List<(string, string)> Uses, string Path)> controls) {
        foreach (var relation in _db.EnumerateRelations(item)) {
            if (!_expandoReferences.Matches(relation.RelationId) || relation.Target.TypeId != _resource || !_db.TryGetFrame(relation.Target, out var resource)) {
                continue;
            }
            var guid = _db.ReadString(resource, _name) ?? "";
            var path = _db.ReadString(resource, _filePath) ?? "CustomControls/" + guid + ".zip";
            var screen = "";
            foreach (var parent in _db.EnumerateRelations(item)) {
                if (parent.Target.TypeId == _screen && _db.TryGetFrame(parent.Target, out var screenFrame)) {
                    screen = _db.ReadString(screenFrame, _name) ?? "";
                    break;
                }
            }
            if (!controls.TryGetValue(guid, out var entry)) {
                entry = (_db.ReadExpandoString(item, "_ContainedControlDisplayName"), [], path);
                controls[guid] = entry;
            }
            entry.Uses.Add((screen, _db.ReadString(item, _name) ?? ""));
            return;
        }
    }

    /// <summary>The files of a control's package: the zip the project keeps in UserFiles, at the resource's path.</summary>
    private List<TiaHmiPackageFile> ReadPackage(string path) {
        var files = new List<TiaHmiPackageFile>();
        var zip = _db.ReadProjectFile("UserFiles/" + path.Replace('\\', '/'));
        if (zip is null) {
            return files;
        }
        try {
            using var archive = new ZipArchive(new MemoryStream(zip), ZipArchiveMode.Read);
            foreach (var entry in archive.Entries.Where(entry => entry.Name.Length != 0).OrderBy(entry => entry.FullName, StringComparer.Ordinal)) {
                using var stream = entry.Open();
                using var copy = new MemoryStream();
                stream.CopyTo(copy);
                files.Add(new TiaHmiPackageFile(entry.FullName.Replace('\\', '/'), copy.ToArray()));
            }
        } catch (InvalidDataException) {
            // A package that is not a zip is reported without files.
        }
        return files;
    }

    // Structures -------------------------------------------------------------------------------------------------------

    /// <summary>The start of each element of an array of structures: u32 size, u32 count, then a u32 ref per element.</summary>
    private static List<int> Elements(ReadOnlySpan<byte> array) {
        var result = new List<int>();
        if (array.Length < 8) {
            return result;
        }
        var count = BinaryPrimitives.ReadInt32LittleEndian(array[4..]);
        for (var i = 0; i < count && 8 + (4 * i) + 4 <= array.Length; i++) {
            var at = BinaryPrimitives.ReadInt32LittleEndian(array[(8 + (4 * i))..]);
            if (at >= 8 && at + 4 <= array.Length) {
                result.Add(at);
            }
        }
        return result;
    }

    /// <summary>A structure's string field by its position: a u32 ref, from the structure's start, to a string.</summary>
    private static string? StringField(ReadOnlySpan<byte> array, int structure, int field) {
        var slot = structure + 4 + (4 * field);
        if (slot + 4 > array.Length) {
            return null;
        }
        var relative = BinaryPrimitives.ReadInt32LittleEndian(array[slot..]);
        var start = structure + relative;
        if (relative <= 0 || start >= array.Length) {
            return null;
        }
        var length = TiaDatabase.ReadVarInt(array, start, out var body);
        var bytes = length - (body - start);
        return bytes < 0 || body + bytes > array.Length ? null : Encoding.UTF8.GetString(array.Slice(body, bytes));
    }
